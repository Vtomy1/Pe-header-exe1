import React from 'react';
import { RichHeader } from '../lib/pe-parser';
import { Binary, Key, Info } from 'lucide-react';

interface RichHeaderViewProps {
  richHeader?: RichHeader;
}

export const RichHeaderView: React.FC<RichHeaderViewProps> = ({ richHeader }) => {
  if (!richHeader || richHeader.entries.length === 0) {
    return (
      <div className="p-6 rounded-xl bg-slate-900 border border-slate-800 text-center space-y-2">
        <div className="inline-flex p-3 rounded-full bg-slate-800 text-slate-400">
          <Binary className="w-5 h-5" />
        </div>
        <h4 className="text-sm font-semibold text-slate-200">No MSVC Rich Header Detected</h4>
        <p className="text-xs text-slate-400 max-w-md mx-auto leading-relaxed">
          The MSVC Rich Header is an undocumented data structure embedded exclusively by Microsoft Visual Studio
          compilers and linkers. Binaries compiled with GCC, MinGW, Clang/LLVM, Go, or stripped of metadata do not contain it.
        </p>
      </div>
    );
  }

  return (
    <div className="space-y-4">
      {/* Header bar */}
      <div className="p-4 rounded-xl bg-slate-900 border border-slate-800 flex flex-wrap items-center justify-between gap-4">
        <div className="flex items-center gap-3">
          <div className="p-2 rounded-lg bg-purple-500/10 border border-purple-500/20 text-purple-400">
            <Binary className="w-5 h-5" />
          </div>
          <div>
            <h3 className="text-sm font-semibold text-slate-100">
              MSVC Rich Header ({richHeader.entries.length} Tool Records)
            </h3>
            <p className="text-xs text-slate-400">
              Compiler, assembler, and linker build metadata decrypted using XOR checksum
            </p>
          </div>
        </div>

        <div className="flex items-center gap-4 text-xs font-mono">
          <div className="flex items-center gap-1.5 text-slate-300">
            <Key className="w-3.5 h-3.5 text-purple-400" />
            <span className="text-slate-500">XOR Key:</span>
            <span className="text-purple-300 font-semibold">
              0x{richHeader.xorKey.toString(16).padStart(8, '0').toUpperCase()}
            </span>
          </div>
          <span className="text-slate-700">|</span>
          <div className="text-slate-300">
            <span className="text-slate-500">Size:</span> {richHeader.size} bytes
          </div>
        </div>
      </div>

      {/* Entries table */}
      <div className="overflow-x-auto border border-slate-800 rounded-xl bg-slate-900 shadow-lg">
        <table className="w-full text-left text-xs border-collapse font-mono">
          <thead>
            <tr className="border-b border-slate-800 bg-slate-950/70 text-slate-400">
              <th className="py-2.5 px-3">#</th>
              <th className="py-2.5 px-3 font-semibold text-slate-200">Component / Tool</th>
              <th className="py-2.5 px-3">Tool ID</th>
              <th className="py-2.5 px-3">Build ID</th>
              <th className="py-2.5 px-3">Visual Studio Version</th>
              <th className="py-2.5 px-3 text-right">Compile Count</th>
            </tr>
          </thead>
          <tbody className="divide-y divide-slate-850 text-slate-300">
            {richHeader.entries.map((entry, idx) => (
              <tr key={idx} className="hover:bg-slate-800/40 transition-colors">
                <td className="py-2 px-3 text-slate-500">{idx + 1}</td>
                <td className="py-2 px-3 font-sans font-medium text-slate-100">
                  {entry.toolName}
                </td>
                <td className="py-2 px-3 text-purple-400">
                  0x{entry.toolId.toString(16).padStart(4, '0').toUpperCase()}
                </td>
                <td className="py-2 px-3 text-slate-400">
                  {entry.buildId}
                </td>
                <td className="py-2 px-3 text-slate-300 font-sans">
                  <span className="px-2 py-0.5 rounded bg-slate-800 text-slate-300 border border-slate-700 text-[11px]">
                    {entry.vsVersion}
                  </span>
                </td>
                <td className="py-2 px-3 text-right tabular-nums font-semibold text-emerald-400">
                  {entry.count}
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>

      <div className="flex items-start gap-2 p-3 rounded-lg bg-slate-950/60 border border-slate-800/80 text-[11px] text-slate-400">
        <Info className="w-4 h-4 text-purple-400 shrink-0 mt-0.5" />
        <span>
          The Rich header is generated by the MSVC linker and contains records of every tool (C++ compiler, MASM, resource compiler, etc.)
          invoked during the build process. It is frequently analyzed in forensic malware investigations to attribute authoring toolchains.
        </span>
      </div>
    </div>
  );
};
