import React, { useState } from 'react';
import { ParsedPE } from '../lib/pe-parser';
import { X, Copy, Check, Download, FileText, Code2, Database } from 'lucide-react';

interface ExportModalProps {
  pe: ParsedPE;
  onClose: () => void;
  sourceUrl?: string;
}

export const ExportModal: React.FC<ExportModalProps> = ({ pe, onClose, sourceUrl }) => {
  const [activeTab, setActiveTab] = useState<'c_struct' | 'json' | 'markdown'>('c_struct');
  const [copied, setCopied] = useState(false);

  // Generate C Struct representation
  const generateCStruct = () => {
    const is64 = pe.optionalHeader?.is64Bit ?? true;
    return `/* Generated by PE Header Inspector */
/* Source: ${sourceUrl || 'Local binary'} */
/* Architecture: ${pe.fileHeader.machineName} */

#include <windows.h>
#include <stdio.h>

/* DOS Header */
IMAGE_DOS_HEADER dosHeader = {
    .e_magic = 0x${pe.dosHeader.e_magic.toString(16).toUpperCase()}, /* MZ */
    .e_cblp = ${pe.dosHeader.e_cblp},
    .e_cp = ${pe.dosHeader.e_cp},
    .e_crlc = ${pe.dosHeader.e_crlc},
    .e_cparhdr = ${pe.dosHeader.e_cparhdr},
    .e_minalloc = ${pe.dosHeader.e_minalloc},
    .e_maxalloc = ${pe.dosHeader.e_maxalloc},
    .e_ss = 0x${pe.dosHeader.e_ss.toString(16)},
    .e_sp = 0x${pe.dosHeader.e_sp.toString(16)},
    .e_csum = 0x${pe.dosHeader.e_csum.toString(16)},
    .e_ip = 0x${pe.dosHeader.e_ip.toString(16)},
    .e_cs = 0x${pe.dosHeader.e_cs.toString(16)},
    .e_lfarlc = 0x${pe.dosHeader.e_lfarlc.toString(16)},
    .e_ovno = ${pe.dosHeader.e_ovno},
    .e_lfanew = 0x${pe.dosHeader.e_lfanew.toString(16).toUpperCase()} /* Offset to NT Header */
};

/* COFF File Header */
IMAGE_FILE_HEADER fileHeader = {
    .Machine = 0x${pe.fileHeader.machine.toString(16).toUpperCase()}, /* ${pe.fileHeader.machineName} */
    .NumberOfSections = ${pe.fileHeader.numberOfSections},
    .TimeDateStamp = 0x${pe.fileHeader.timeDateStamp.toString(16).toUpperCase()}, /* ${pe.fileHeader.timeDateString} */
    .PointerToSymbolTable = 0x${pe.fileHeader.pointerToSymbolTable.toString(16)},
    .NumberOfSymbols = ${pe.fileHeader.numberOfSymbols},
    .SizeOfOptionalHeader = ${pe.fileHeader.sizeOfOptionalHeader},
    .Characteristics = 0x${pe.fileHeader.characteristics.toString(16).toUpperCase()}
};

/* Optional Header (${is64 ? 'IMAGE_OPTIONAL_HEADER64' : 'IMAGE_OPTIONAL_HEADER32'}) */
${is64 ? 'IMAGE_OPTIONAL_HEADER64' : 'IMAGE_OPTIONAL_HEADER32'} optionalHeader = {
    .Magic = 0x${pe.optionalHeader?.magic.toString(16).toUpperCase()},
    .MajorLinkerVersion = ${pe.optionalHeader?.majorLinkerVersion},
    .MinorLinkerVersion = ${pe.optionalHeader?.minorLinkerVersion},
    .SizeOfCode = 0x${pe.optionalHeader?.sizeOfCode.toString(16).toUpperCase()},
    .SizeOfInitializedData = 0x${pe.optionalHeader?.sizeOfInitializedData.toString(16).toUpperCase()},
    .SizeOfUninitializedData = 0x${pe.optionalHeader?.sizeOfUninitializedData.toString(16).toUpperCase()},
    .AddressOfEntryPoint = 0x${pe.optionalHeader?.addressOfEntryPoint.toString(16).toUpperCase()},
    .BaseOfCode = 0x${pe.optionalHeader?.baseOfCode.toString(16).toUpperCase()},
    .ImageBase = ${pe.optionalHeader?.imageBase},
    .SectionAlignment = 0x${pe.optionalHeader?.sectionAlignment.toString(16).toUpperCase()},
    .FileAlignment = 0x${pe.optionalHeader?.fileAlignment.toString(16).toUpperCase()},
    .Subsystem = ${pe.optionalHeader?.subsystem}, /* ${pe.optionalHeader?.subsystemName} */
    .DllCharacteristics = 0x${pe.optionalHeader?.dllCharacteristics.toString(16).toUpperCase()}
};

/* Sections (${pe.sections.length}) */
IMAGE_SECTION_HEADER sections[${pe.sections.length}] = {
${pe.sections
  .map(
    (s) => `    {
        .Name = "${s.name}",
        .Misc.VirtualSize = 0x${s.virtualSize.toString(16).toUpperCase()},
        .VirtualAddress = 0x${s.virtualAddress.toString(16).toUpperCase()},
        .SizeOfRawData = 0x${s.sizeOfRawData.toString(16).toUpperCase()},
        .PointerToRawData = 0x${s.pointerToRawData.toString(16).toUpperCase()},
        .Characteristics = 0x${s.characteristics.toString(16).toUpperCase()} /* ${s.permissions} */
    }`
  )
  .join(',\n')}
};`;
  };

  // Generate JSON
  const generateJSON = () => {
    const jsonOutput = {
      source: sourceUrl || 'Local binary',
      architecture: pe.fileHeader.machineName,
      subsystem: pe.optionalHeader?.subsystemName,
      dosHeader: pe.dosHeader,
      fileHeader: pe.fileHeader,
      optionalHeader: pe.optionalHeader,
      richHeader: pe.richHeader,
      sections: pe.sections.map((s) => ({
        name: s.name,
        virtualSize: `0x${s.virtualSize.toString(16)}`,
        virtualAddress: `0x${s.virtualAddress.toString(16)}`,
        sizeOfRawData: `0x${s.sizeOfRawData.toString(16)}`,
        pointerToRawData: `0x${s.pointerToRawData.toString(16)}`,
        permissions: s.permissions,
        entropy: s.entropy,
        characteristics: `0x${s.characteristics.toString(16)}`,
      })),
      security: pe.security,
      exportDirectory: pe.exportDirectory
        ? {
            dllName: pe.exportDirectory.dllName,
            baseOrdinal: pe.exportDirectory.base,
            totalFunctions: pe.exportDirectory.numberOfFunctions,
            namedExports: pe.exportDirectory.numberOfNames,
            functions: pe.exportDirectory.functions.map((f) => ({
              ordinal: f.ordinal,
              name: f.name || null,
              rva: `0x${f.rva.toString(16).toUpperCase()}`,
              isForwarder: f.isForwarder,
              forwarder: f.forwarder || null,
            })),
          }
        : null,
      imports: pe.imports?.map((m) => ({
        module: m.name,
        functionCount: m.functions.length,
        functionsSample: m.functions.slice(0, 10).map((f) => f.name),
      })),
    };
    return JSON.stringify(jsonOutput, null, 2);
  };

  // Generate Markdown
  const generateMarkdown = () => {
    return `# PE Header Inspection Report

**Binary Target**: ${sourceUrl || 'Local binary'}  
**Machine Architecture**: ${pe.fileHeader.machineName}  
**Subsystem**: ${pe.optionalHeader?.subsystemName || 'N/A'}  
**Linker Version**: ${pe.optionalHeader?.majorLinkerVersion}.${pe.optionalHeader?.minorLinkerVersion}  
**Compilation Timestamp**: ${pe.fileHeader.timeDateString}  
**Image Base**: ${pe.optionalHeader?.imageBase}  
**Entry Point RVA**: 0x${pe.optionalHeader?.addressOfEntryPoint.toString(16).toUpperCase()}  

---

## Exploit Mitigations
- **ASLR**: ${pe.security.aslr ? 'Enabled' : 'Disabled'}
- **High Entropy VA (64-bit)**: ${pe.security.highEntropyVa ? 'Enabled' : 'Disabled'}
- **DEP/NX**: ${pe.security.dep ? 'Enabled' : 'Disabled'}
- **Control Flow Guard (CFG)**: ${pe.security.cfg ? 'Enabled' : 'Disabled'}
- **Authenticode Signature**: ${pe.security.authenticode ? `Signed (${(pe.security.certSize / 1024).toFixed(1)} KB)` : 'Unsigned'}
- **Managed .NET**: ${pe.security.isDotNet ? 'Yes' : 'Native'}

---

## Export Directory (${pe.exportDirectory ? `${pe.exportDirectory.dllName} - ${pe.exportDirectory.functions.length} functions` : 'None'})
${
  pe.exportDirectory
    ? `**DLL Module Name**: \`${pe.exportDirectory.dllName}\`  
**Base Ordinal**: ${pe.exportDirectory.base}  
**Total Functions**: ${pe.exportDirectory.numberOfFunctions} (${pe.exportDirectory.numberOfNames} named)

| Ordinal | Function Name | RVA | Type |
|---|---|---|---|
${pe.exportDirectory.functions
  .map(
    (f) =>
      `| #${f.ordinal} | \`${f.name || '[Ordinal Only]'}\` | 0x${f.rva.toString(16).toUpperCase()} | ${f.isForwarder ? `Forwarded to \`${f.forwarder}\`` : 'Direct Export'} |`
  )
  .join('\n')}`
    : '_No export directory present in this binary._'
}

---

## Sections (${pe.sections.length})
| Name | Virtual Size | Virtual Address (RVA) | Raw Size | Raw Offset | Perms | Entropy |
|---|---|---|---|---|---|---|
${pe.sections
  .map(
    (s) =>
      `| \`${s.name}\` | 0x${s.virtualSize.toString(16).toUpperCase()} | 0x${s.virtualAddress.toString(16).toUpperCase()} | 0x${s.sizeOfRawData.toString(16).toUpperCase()} | 0x${s.pointerToRawData.toString(16).toUpperCase()} | \`${s.permissions}\` | ${s.entropy ?? 'N/A'} |`
  )
  .join('\n')}

---
*Generated by PE Header Inspector*
`;
  };

  const getContent = () => {
    switch (activeTab) {
      case 'c_struct':
        return generateCStruct();
      case 'json':
        return generateJSON();
      case 'markdown':
        return generateMarkdown();
    }
  };

  const handleCopy = () => {
    navigator.clipboard.writeText(getContent());
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownloadText = () => {
    const ext = activeTab === 'c_struct' ? 'c' : activeTab === 'json' ? 'json' : 'md';
    const blob = new Blob([getContent()], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `pe_header_${Date.now()}.${ext}`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const handleDownloadRaw = () => {
    const blob = new Blob([pe.data.buffer as ArrayBuffer], { type: 'application/octet-stream' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `pe_header_raw_${Date.now()}.bin`;
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="fixed inset-0 z-50 bg-slate-950/80 backdrop-blur-sm flex items-center justify-center p-4">
      <div className="bg-slate-900 border border-slate-800 rounded-2xl w-full max-w-4xl max-h-[90vh] flex flex-col shadow-2xl overflow-hidden">
        {/* Header */}
        <div className="flex items-center justify-between px-6 py-4 border-b border-slate-800 bg-slate-900">
          <div className="flex items-center gap-2">
            <h3 className="text-base font-semibold text-slate-100">Export PE Analysis</h3>
            <span className="text-slate-500">·</span>
            <span className="text-xs text-slate-400 font-mono">{pe.fileHeader.machineName}</span>
          </div>

          <button
            onClick={onClose}
            className="p-1 rounded-lg text-slate-400 hover:text-white hover:bg-slate-800 transition-colors"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Tab Selection */}
        <div className="flex items-center justify-between px-6 py-2.5 bg-slate-950/60 border-b border-slate-800 text-xs">
          <div className="flex items-center gap-2">
            <button
              onClick={() => setActiveTab('c_struct')}
              className={`flex items-center gap-1.5 px-3 py-1.5 rounded-lg font-medium transition-colors ${
                activeTab === 'c_struct'
                  ? 'bg-indigo-600 text-white'
                  : 'text-slate-400 hover:text-slate-200 hover:bg-slate-800'
              }`}
            >
              <Code2 className="w-4 h-4" />
              <span>C Header Structs</span>
            </button>
            <button
              onClick={() => setActiveTab('json')}
              className={`flex items-center gap-1.5 px-3 py-1.5 rounded-lg font-medium transition-colors ${
                activeTab === 'json'
                  ? 'bg-indigo-600 text-white'
                  : 'text-slate-400 hover:text-slate-200 hover:bg-slate-800'
              }`}
            >
              <Database className="w-4 h-4" />
              <span>JSON Schema</span>
            </button>
            <button
              onClick={() => setActiveTab('markdown')}
              className={`flex items-center gap-1.5 px-3 py-1.5 rounded-lg font-medium transition-colors ${
                activeTab === 'markdown'
                  ? 'bg-indigo-600 text-white'
                  : 'text-slate-400 hover:text-slate-200 hover:bg-slate-800'
              }`}
            >
              <FileText className="w-4 h-4" />
              <span>Markdown Report</span>
            </button>
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={handleCopy}
              className="flex items-center gap-1 px-3 py-1.5 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-200 border border-slate-700 font-medium transition-colors"
            >
              {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
              <span>{copied ? 'Copied' : 'Copy'}</span>
            </button>
            <button
              onClick={handleDownloadText}
              className="flex items-center gap-1 px-3 py-1.5 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-200 border border-slate-700 font-medium transition-colors"
            >
              <Download className="w-3.5 h-3.5" />
              <span>Save File</span>
            </button>
            <button
              onClick={handleDownloadRaw}
              className="flex items-center gap-1 px-3 py-1.5 rounded-lg bg-indigo-950/70 hover:bg-indigo-900 text-indigo-300 border border-indigo-700/50 font-medium transition-colors"
              title="Download the raw fetched header byte buffer"
            >
              <Download className="w-3.5 h-3.5" />
              <span>Download Raw Binary</span>
            </button>
          </div>
        </div>

        {/* Code Content */}
        <div className="flex-1 overflow-auto p-6 bg-slate-950 font-mono text-xs text-slate-300 select-text">
          <pre className="whitespace-pre">{getContent()}</pre>
        </div>
      </div>
    </div>
  );
};
